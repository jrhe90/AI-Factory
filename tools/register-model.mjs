#!/usr/bin/env node
// Register a procedural three.js factory (normally img2threejs output) with the Line Builder.
//
//   node tools/register-model.mjs <slug> <factory.ts|factory.js> [options]
//
//   --factory <name>   exported function that returns the THREE.Group (default: auto-detect)
//   --name <text>      display name            (default: captures/<slug>/capture.json, else slug)
//   --size w,h,d       real size in metres     (default: capture.json size)
//   --role station|equipment                   (default: capture.json role, else station)
//   --rotate <deg>     yaw so the object's front faces +z and flow runs along +x (default 0)
//   --source <text>    provenance note stored in model.json
//
// Writes models/captured/<slug>/model.js + model.json and adds the slug to
// models/captured/index.json. TypeScript is stripped with esbuild (fetched by npx); imports
// such as 'three' and 'three/examples/jsm/...' are kept and resolved by the page's import map.
import fs from 'node:fs/promises';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MODELS = path.join(ROOT, 'models', 'captured');
const ESBUILD = 'esbuild@0.24.0';

function fail(msg) {
  console.error(`register-model: ${msg}`);
  process.exit(1);
}

const args = process.argv.slice(2);
const opts = {};
const pos = [];
for (let i = 0; i < args.length; i++) {
  if (args[i].startsWith('--')) opts[args[i].slice(2)] = args[++i];
  else pos.push(args[i]);
}
const [slug, src] = pos;
if (!slug || !src) fail('usage: node tools/register-model.mjs <slug> <factory.ts|js> [--factory name] [--size w,h,d] [--role station|equipment] [--rotate deg]');
if (!/^[a-z0-9][a-z0-9-]{0,47}$/.test(slug)) fail(`"${slug}" is not a valid slug (lowercase letters, digits and dashes)`);

let capture = {};
try {
  capture = JSON.parse(await fs.readFile(path.join(ROOT, 'captures', slug, 'capture.json'), 'utf8'));
} catch {
  // registering a model that did not come through capture.html
}

const source = await fs.readFile(src, 'utf8').catch(() => fail(`cannot read ${src}`));
let js = source;
if (/\.tsx?$/.test(src)) {
  try {
    js = execFileSync('npx', ['--yes', ESBUILD, '--loader=ts', '--format=esm', '--target=es2020', '--log-level=warning'], { input: source, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
  } catch (err) {
    fail(`esbuild could not transpile ${src}\n${err.stderr ?? err.message}`);
  }
}

// Find the factory: an exported function returning THREE.Group, preferring create*Model
const exported = [...source.matchAll(/export\s+function\s+(\w+)\s*\(([^)]*)\)\s*(?::\s*([\w.<>]+))?/g)].map((m) => ({ name: m[1], returns: m[3] ?? '' }));
const factory = opts.factory
  ?? exported.find((f) => /^create\w*Model$/.test(f.name) && /Group/.test(f.returns))?.name
  ?? exported.find((f) => /^create\w*Model$/.test(f.name))?.name
  ?? exported.find((f) => /Group/.test(f.returns))?.name;
if (!factory) fail(`no exported factory found in ${src}; pass --factory <name>`);
if (!new RegExp(`export\\s+function\\s+${factory}\\b`).test(source)) fail(`${src} does not export a function named ${factory}`);

const size = opts.size ? opts.size.split(',').map(Number) : capture.size ?? null;
if (size && (size.length !== 3 || size.some((v) => v !== null && !(v > 0)))) fail('--size must be three positive numbers: width,height,depth');
const role = opts.role ?? capture.role ?? 'station';
if (!['station', 'equipment'].includes(role)) fail('--role must be station or equipment');

const dir = path.join(MODELS, slug);
await fs.mkdir(dir, { recursive: true });
await fs.writeFile(path.join(dir, 'model.js'), `// Generated by tools/register-model.mjs from ${path.basename(src)} – edit the source and re-register.\n${js}`);
const meta = {
  slug,
  name: opts.name ?? capture.name ?? slug,
  role,
  factory,
  size, // [width, height, depth] in metres; the builder scales the model to fit
  rotationY: Number(opts.rotate ?? 0),
  source: opts.source ?? (capture.slug ? `img2threejs reconstruction of captures/${slug}` : path.basename(src)),
  approximate: true, // single-photo reconstructions cannot see hidden sides
  registeredAt: new Date().toISOString(),
};
await fs.writeFile(path.join(dir, 'model.json'), JSON.stringify(meta, null, 2) + '\n');

const idxFile = path.join(MODELS, 'index.json');
let idx = { models: [] };
try {
  idx = JSON.parse(await fs.readFile(idxFile, 'utf8'));
} catch {
  // first model
}
idx.models = (idx.models ?? []).filter((m) => m.slug !== slug);
idx.models.push({ slug, name: meta.name, role });
idx.models.sort((a, b) => a.name.localeCompare(b.name));
await fs.writeFile(idxFile, JSON.stringify(idx, null, 2) + '\n');

if (capture.slug) {
  capture.status = 'modelled';
  await fs.writeFile(path.join(ROOT, 'captures', slug, 'capture.json'), JSON.stringify(capture, null, 2) + '\n');
}
console.log(`Registered "${meta.name}" (${role}, factory ${factory}) → models/captured/${slug}/`);
